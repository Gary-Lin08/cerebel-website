import {chromium} from '@playwright/test';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || "/usr/bin/google-chrome",args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5177/experience.html');
await page.waitForSelector('.xp.is-interactive');
await page.waitForTimeout(1800);
await page.screenshot({path:'/tmp/cerebel-green-opening.png'});
await page.mouse.move(550,400);await page.waitForTimeout(1800);await page.screenshot({path:'/tmp/cerebel-reveal.png'});
await page.evaluate(()=>scrollTo(0,1.9*innerHeight));await page.waitForTimeout(2200);
await page.mouse.move(1000,180);await page.waitForTimeout(1800);await page.screenshot({path:'/tmp/cerebel-light-top.png'});
await page.mouse.move(1000,740);await page.waitForTimeout(2200);await page.screenshot({path:'/tmp/cerebel-light-bottom.png'});
await page.evaluate(()=>scrollTo(0,6*innerHeight));await page.waitForTimeout(2200);
await page.locator('.muscle-entry').click();await page.waitForTimeout(2200);await page.screenshot({path:'/tmp/cerebel-anatomy.png'});
await page.locator('.muscle-orbit nav button').last().click();await page.waitForTimeout(1200);await page.screenshot({path:'/tmp/cerebel-anatomy-left.png'});
await page.keyboard.press('Escape');
await page.locator('[data-group="Benchmark"]').first().click();await page.waitForTimeout(2500);await page.screenshot({path:'/tmp/cerebel-benchmark.png'});
await page.locator('[data-group="Glasses"]').first().click();
await page.waitForTimeout(4500);await page.screenshot({path:'/tmp/cerebel-studio-glasses.png'});
if(errors.length)throw Error(errors.join('\n'));
console.log('Visual sequence completed without page errors.');await browser.close();
